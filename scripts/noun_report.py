"""Runs the NOUN 2026_2 import end to end on a temporary database and writes docs/NOUN_IMPORT_REPORT.md.

Every number in the report is produced by this run. Usage: python -m scripts.noun_report [--seeds 5]
"""
from __future__ import annotations

import argparse
import io
import os
import platform
import statistics
import sys
import time
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PDF = os.path.join(ROOT, "data", "noun", "2026_2_E-Exam_Draft_Timetable_57.pdf")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "NOUN_IMPORT_REPORT.md"))
    args = ap.parse_args()
    sys.path.insert(0, ROOT)
    from sqlalchemy import func, select
    from algorithm import GAConfig, run_genetic_algorithm
    from algorithm.loader import load_scheduling_data
    from auth.service import _create_user
    from database import session_scope
    from database.models import (Classroom, Course, Department, ExamEntry, Lecturer, StudentGroup, TimeSlot, Timetable)
    from exports import exam_export, excel_export, pdf_export
    from importers import noun_exam_pdf as nx
    from importers.noun_import import build_report
    from scripts.benchmark import _fresh_db
    from services import dataset_service as dsv, exam_service as ex, synthetic_service as syn
    from services.generation_service import entries_to_drafts
    from validation import timetable_validator as tv

    L = ["# NOUN 2026_2 E-EXAM draft timetable: import and test report", "",
         f"Generated by `python -m scripts.noun_report` on {date.today().isoformat()} (Python {platform.python_version()}, {platform.system()} {platform.machine()}). "
         "Every figure below was produced by that run. The source PDF is a DRAFT timetable; the dataset is a test dataset, not an approved institutional timetable.", ""]
    t0 = time.perf_counter()
    r = nx.extract_noun_exam_pdf(PDF)
    t_extract = time.perf_counter() - t0
    rep = build_report(r)
    L += ["## 1. Extraction statistics", "", f"Extraction time: {t_extract:.1f} s. Method: positional text extraction (pdfplumber) assigned to table cells by x position, "
          "to days by the left-edge day label and to sessions by the time header above each day. See `importers/noun_exam_pdf.py`.", "",
          "| Item | Value |", "|---|---|"]
    for label, key in [("Pages processed", None), ("Examination days identified", "days_identified"), ("Examination sessions identified", "sessions_identified"),
                       ("Course entries extracted", "entries_extracted"), ("Unique course codes", "unique_course_codes"), ("Batch A entries", "batch_a_entries"),
                       ("Batch B entries", "batch_b_entries"), ("NOUN-prefixed entries", "noun_prefixed_entries"), ("Entries with missing course codes", "missing_course_codes"),
                       ("Entries with missing course titles", "missing_course_titles"), ("Entries flagged for manual review", "needs_manual_review"),
                       ("Independent plain-text code-token count", "independent_token_count")]:
        L.append(f"| {label} | {rep['pages_processed']} of {rep['pages_total']} |" if key is None else f"| {label} | {rep[key]} |")
    L += [f"| Independent count equals extracted count | {rep['independent_count_matches']} |", f"| Page problems | {rep['page_problems'] or 'none'} |", ""]
    L += ["Records per PDF page: " + ", ".join(f"page {k}: {v}" for k, v in rep["entries_by_page"].items()) + ".", "",
          "Records per examination day: " + ", ".join(f"day {k}: {v}" for k, v in rep["entries_by_day"].items()) + ".", "",
          "Days whose final session is at 3pm: " + ", ".join(str(d.day_no) for d in r.days if d.sessions[-1].label == "3pm") + "; all other days end at 2pm.", ""]
    flagged = [e for e in r.entries if e.needs_review]
    L += ["### Records flagged for manual review", "", "Each of these titles is a strict prefix of another title in the same document that continues in the middle of a word, so the printed title may be clipped. They are stored exactly as printed.", "",
          "| Day | Page | Code | Title as printed |", "|---|---|---|---|"] + [f"| {e.day_no} | {e.page_no} | {e.course_code} | {e.course_title} |" for e in flagged] + [""]

    _fresh_db("small")
    with session_scope() as s:
        admin = _create_user(s, "Report Admin", "report@example.test", "StrongPass123", "SUPER_ADMIN"); s.commit()
        tables = (Department, Lecturer, Course, Classroom, StudentGroup, Timetable, TimeSlot)
        before = {m.__tablename__: s.scalar(select(func.count()).select_from(m)) for m in tables}
        out = dsv.import_extraction(s, admin, r)
        again = dsv.import_extraction(s, admin, r)
        n_rows = s.scalar(select(func.count(ExamEntry.id)))
        rv = dsv.revalidate_dataset(s, admin, out.dataset_id)
        L += ["## 2. Import", "", f"- First import: status {out.status}, records imported {out.imported}, duplicates prevented {out.duplicates_prevented}.",
              f"- Second import of the same PDF: status {again.status}, records imported {again.imported}, duplicates prevented {again.duplicates_prevented}.",
              f"- Examination records stored in the database: {n_rows}.",
              f"- Existing demonstration records before and after the import: {before} and "
              f"{ {m.__tablename__: s.scalar(select(func.count()).select_from(m)) for m in tables} }.",
              f"- Revalidation from the database: {rv['status']} ({sum(c['passed'] for c in rv['checks'])} of {len(rv['checks'])} checks passed).", ""]
        pdf = exam_export.export_exam_pdf(s, admin, out.dataset_id)
        xls = exam_export.export_exam_excel(s, admin, out.dataset_id)
        L += [f"- Examination timetable exports: PDF {len(pdf):,} bytes, Excel {len(xls):,} bytes.", ""]
        snap = [(e.record_key, e.course_code, e.course_title) for e in s.scalars(select(ExamEntry).order_by(ExamEntry.id))]

        syn_ds = syn.build_synthetic_lecture_dataset(s, admin, out.dataset_id)
        sr = syn_ds.report
        L += ["## 3. Synthetic test data layer", "", "SYNTHETIC TEST DATA. Only course codes and titles come from the PDF. Everything else was invented by the generator "
              "(`services/synthetic_service.py`, seed " + str(sr["seed"]) + ") and is marked TEST DATA / SYN- in names, codes, e-mail addresses and descriptions.", "",
              f"- Courses: {sr['courses']} (non-NOUN-prefixed, non-batch entries whose code prefix is one of {', '.join(sr['prefixes'])}; discipline inferred from the prefix, not stated in the PDF).",
              f"- Lecturers: {sr['lecturers']}; rooms: {sr['rooms']}; student groups: {sr['groups']} (levels {sr['levels']}, at most {sr['stream_size']} courses per group); academic session {sr['academic_session']}, semester {sr['semester']}.",
              "- Each course gets 2 or 3 weekly teaching hours (default split into blocks of at most 2 hours) and one lecturer; lab-type titles require a computer laboratory.", ""]

        dept = syn.department_id_of(s, syn_ds)
        from database.models import DatasetMember
        syn_rooms = list(s.scalars(select(DatasetMember.entity_id).where(DatasetMember.dataset_id == syn_ds.id, DatasetMember.entity == "classroom")))
        data = load_scheduling_data(s, sr["academic_session"], sr["semester"], dept, room_ids=syn_rooms)
        L += ["## 4. Genetic Algorithm tests on the synthetic lecture data", "", f"{len(data.sessions)} required teaching sessions, {len(data.rooms)} rooms (the synthetic rooms only; the institution's own rooms are never used), {len(data.windows)} teaching days. "
              f"Seeds 1 to {args.seeds}. Hard violations are counted by the algorithm; every saved timetable is additionally checked by the independent validator.", "",
              "### 4.1 Standard run (population 40, up to 100 generations, mutation 0.02, crossover 0.85, elitism 2)", "",
              "| Seed | Initial hard | Final hard | Initial soft penalty | Final soft penalty | Generations | Time s | Independent validation |", "|---|---|---|---|---|---|---|---|"]
        soft_i, soft_f, times = [], [], []
        parent = None
        for seed in range(1, args.seeds + 1):
            o = syn.generate_lecture_timetable(s, admin, syn_ds, GAConfig(population_size=40, max_generations=100, seed=seed), parent_id=parent)
            h0 = o.result.history[0]
            soft_i.append(h0["soft_penalty"]); soft_f.append(o.result.evaluation.soft_weighted); times.append(o.result.elapsed_seconds)
            L.append(f"| {seed} | {h0['hard_violations']} | {o.result.evaluation.hard_total} | {h0['soft_penalty']:.1f} | {o.result.evaluation.soft_weighted:.1f} | "
                     f"{o.result.generations_run} | {o.result.elapsed_seconds:.2f} | {'valid, ' + str(len(o.conflicts)) + ' violations' if o.is_valid else str(len(o.conflicts)) + ' violations'} |")
        L += ["", f"Mean soft penalty: {statistics.mean(soft_i):.1f} initial, {statistics.mean(soft_f):.1f} final. Mean time {statistics.mean(times):.2f} s.", ""]
        tts = list(s.scalars(select(Timetable).where(Timetable.department_id == dept).order_by(Timetable.id)))
        drafts_ok = all(not tv.validate_entries(s, entries_to_drafts(t.entries), sr["academic_session"], sr["semester"], dept) for t in tts if t.is_valid)
        L += [f"Timetables saved: {len(tts)}; all valid ones re-validated again independently: {drafts_ok}. Required sessions per timetable: {len(data.sessions)}; scheduled in the latest: {len(tts[-1].entries)}.", ""]
        L += ["### 4.2 Random-start run (heuristic placement switched off, so evolution has to resolve the conflicts)", "", "Population 60, up to 300 generations, stop at the first conflict-free timetable.", "",
              "| Seed | Initial hard violations | Final hard violations | Generations | Time s |", "|---|---|---|---|---|"]
        for seed in range(1, args.seeds + 1):
            res = run_genetic_algorithm(data, GAConfig(population_size=60, max_generations=300, stagnation_threshold=300, heuristic_ratio=0.0, stop_on_zero_hard=True, seed=seed))
            L.append(f"| {seed} | {res.history[0]['hard_violations']} | {res.evaluation.hard_total} | {res.generations_run} | {res.elapsed_seconds:.2f} |")
        L += [""]
        cmpres = None
        from services import comparison_service as cmp
        if len(tts) >= 2:
            cmpres = cmp.compare_timetables(s, admin, tts[-1].id, tts[0].id)
        L += ["### 4.3 Comparison, export and component coverage", "", f"- Timetable comparison (latest versus first): {cmpres.verdict if cmpres else 'n/a'} Sessions that differ: {len(cmpres.changes) if cmpres else 0}.",
              f"- Lecture timetable PDF {len(pdf_export.export_timetable_pdf(s, admin, tts[-1].id)):,} bytes; Excel {len(excel_export.export_timetable_excel(s, admin, tts[-1].id)):,} bytes.",
              "- Initial population, fitness evaluation, tournament selection, crossover, mutation, elitism, termination and reproducibility are covered by `tests/test_algorithm.py`; these runs exercise all of them on the synthetic NOUN-derived data.", ""]

        # ---- conflicts
        c1 = ex.detect_group_conflicts(s, admin, out.dataset_id, syn_ds.id)
        c2 = ex.detect_group_conflicts(s, admin, out.dataset_id, syn_ds.id, 120)
        par = ex.parallel_summary(s, admin, out.dataset_id)
        L += ["## 5. Examination conflict analysis", "", f"- Parallel examination sessions: {len(par)} sessions, up to {max(p['parallel_examinations'] for p in par)} examinations at once. Parallel examinations are NOT conflicts.",
              f"- Synthetic student groups checked: {c1['groups_checked']} ({c1['courses_checked']} course registrations). Genuine conflicts (same group, same session): {len(c1['conflicts'])}; "
              f"with an assumed 120-minute duration: {len(c2['conflicts'])}.",
              "- The groups are synthetic, so any conflict listed here describes how the test groups were composed, not NOUN students."]
        for c in c1["conflicts"]:
            L.append(f"  - {c['group']}: {c['course_a']} and {c['course_b']} on day {c['day_no']} at {c['time_a']}.")
        L += [""]
        unchanged = snap == [(e.record_key, e.course_code, e.course_title) for e in s.scalars(select(ExamEntry).order_by(ExamEntry.id))]
        L += [f"- Original examination schedule unchanged after all lecture generations: {unchanged}.", ""]

        # ---- removal
        info = dsv.remove_dataset(s, admin, syn_ds.id)
        after_syn = {m.__tablename__: s.scalar(select(func.count()).select_from(m)) for m in tables}
        dsv.remove_dataset(s, admin, out.dataset_id)
        L += ["## 6. Removal", "", f"- Synthetic dataset removed: {info}.", f"- Institution records after removing everything: {after_syn} (equal to the original counts: {after_syn == before}).",
              f"- Examination records remaining: {s.scalar(select(func.count(ExamEntry.id)))}.", ""]
    L += ["## 7. Limitations", "",
          "- Titles that the source itself clips are preserved as printed; only those that another title in the document continues are flagged (10 records). Other clipped titles cannot be detected automatically.",
          "- The faculty grouping is only known per range of days (days 1 to 8 and days 9 to 16) from the PDF legend; the PDF does not say which faculty a course belongs to.",
          "- The PDF gives start times only. Examination durations are unknown; the conflict test is slot-based unless a duration is assumed.",
          "- The extractor is written for this document's layout; a differently laid-out PDF will be reported as INVALID or NEEDS_REVIEW rather than imported silently."]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
