"""Reproducible Genetic Algorithm evaluation on demonstration datasets.

Usage: python -m scripts.benchmark [--seeds 5] [--out docs/benchmark_results.md]
Uses a temporary SQLite database. Every number written to the report comes from an actual run of this script.
"""
from __future__ import annotations

import argparse
import os
import platform
import statistics
import sys
import tempfile
from datetime import date

from alembic import command
from alembic.config import Config

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _fresh_db(size: str):
    from database import connection, session_scope
    from services.demo_data import seed_demo
    path = os.path.join(tempfile.mkdtemp(), f"bench_{size}.db")
    url = f"sqlite:///{path}"
    os.environ["ALEMBIC_DATABASE_URL"] = url
    cfg = Config(os.path.join(ROOT, "alembic.ini"))
    cfg.set_main_option("script_location", os.path.join(ROOT, "migrations"))
    command.upgrade(cfg, "head")
    connection.configure(url)
    with session_scope() as s:
        seed_demo(s, size)


def _load(size: str):
    from algorithm.loader import load_scheduling_data
    from database import session_scope
    _fresh_db(size)
    with session_scope() as s:
        return load_scheduling_data(s, "2025/2026", "FIRST")


def _run(data, seed, **kw):
    from algorithm import GAConfig, run_genetic_algorithm
    cfg = GAConfig(seed=seed, **kw)
    r = run_genetic_algorithm(data, cfg)
    return r


def _fmt(vals, f="{:.2f}"):
    return f.format(statistics.mean(vals)) + (f" (sd {f.format(statistics.pstdev(vals))})" if len(vals) > 1 else "")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "benchmark_results.md"))
    args = ap.parse_args()
    seeds = list(range(1, args.seeds + 1))
    out = [f"# Genetic Algorithm benchmark results", "",
           f"Generated by `python -m scripts.benchmark` on {date.today().isoformat()} (Python {platform.python_version()}, "
           f"{platform.system()} {platform.machine()}). All figures are measured; datasets are the DEMONSTRATION data from "
           f"`services/demo_data.py`, not real institutional data. Each row aggregates {len(seeds)} seeds "
           f"({seeds[0]} to {seeds[-1]}). Hard violations are counted by the Genetic Algorithm's own evaluator; the application "
           "additionally validates every saved timetable with an independent validator.", ""]

    # ---- 1. dataset size ----
    out += ["## 1. Effect of dataset size", "", "Population 40, up to 150 generations, mutation 0.02, crossover 0.85, elitism 2, stagnation 50.", "",
            "| Dataset | Sessions | Runs conflict-free | Initial best hard violations (mean) | Final hard violations (mean) | Initial soft penalty (mean) | Final soft penalty (mean) | Generations (mean) | Time s (mean) |",
            "|---|---|---|---|---|---|---|---|---|"]
    datasets = {}
    for size in ("small", "medium", "large", "tight"):
        data = _load(size)
        datasets[size] = data
        rs = [_run(data, sd, population_size=40, max_generations=150, stagnation_threshold=50) for sd in seeds]
        hist0 = [r.history[0] for r in rs]
        out.append(f"| {size} | {len(data.sessions)} | {sum(1 for r in rs if r.is_conflict_free)}/{len(rs)} | "
                   f"{_fmt([h['hard_violations'] for h in hist0], '{:.1f}')} | {_fmt([r.evaluation.hard_total for r in rs], '{:.1f}')} | "
                   f"{_fmt([h['soft_penalty'] for h in hist0], '{:.1f}')} | {_fmt([r.evaluation.soft_weighted for r in rs], '{:.1f}')} | "
                   f"{_fmt([r.generations_run for r in rs], '{:.0f}')} | {_fmt([r.elapsed_seconds for r in rs])} |")
    # ---- 2. parameter sweep on medium ----
    data = datasets["medium"]
    out += ["", "## 2. Parameter sensitivity (medium dataset)", "", "One parameter varied at a time from: population 40, 100 generations, mutation 0.02, crossover 0.85, elitism 2.", "",
            "| Parameter | Value | Runs conflict-free | Final hard (mean) | Final soft penalty (mean) | Time s (mean) |", "|---|---|---|---|---|---|"]
    sweeps = [("population_size", [10, 20, 40, 80]), ("mutation_rate", [0.0, 0.005, 0.02, 0.05, 0.1]),
              ("crossover_rate", [0.0, 0.5, 0.85, 1.0]), ("elite_size", [0, 2, 8]), ("max_generations", [10, 50, 100, 200])]
    base = dict(population_size=40, max_generations=100, mutation_rate=0.02, crossover_rate=0.85, elite_size=2, stagnation_threshold=1000)
    for name, values in sweeps:
        for v in values:
            kw = {**base, name: v}
            rs = [_run(data, sd, **kw) for sd in seeds]
            out.append(f"| {name} | {v} | {sum(1 for r in rs if r.is_conflict_free)}/{len(rs)} | {_fmt([r.evaluation.hard_total for r in rs], '{:.1f}')} | "
                       f"{_fmt([r.evaluation.soft_weighted for r in rs], '{:.1f}')} | {_fmt([r.elapsed_seconds for r in rs])} |")
    # ---- 3. conflict resolution without the heuristic start ----
    out += ["", "## 3. Conflict resolution from a purely random initial population", "",
            "The heuristic initialiser alone already produces conflict-free timetables on these demonstration datasets, so section 1 "
            "mostly measures soft-constraint optimisation. To measure the evolutionary search itself, the heuristic share of the "
            "initial population is set to 0 (constrained-random placement only). Population 60, up to 300 generations, stagnation 300.", "",
            "| Dataset | Sessions | Initial best hard violations (mean) | Final hard violations (mean) | Runs conflict-free | Generations to first conflict-free (mean, conflict-free runs) | Time s (mean) |",
            "|---|---|---|---|---|---|---|"]
    for size in ("medium", "large", "tight"):
        d = datasets[size]
        rs = [_run(d, sd, population_size=60, max_generations=300, stagnation_threshold=300, heuristic_ratio=0.0, stop_on_zero_hard=True) for sd in seeds]
        firsts = [next((h["generation"] for h in r.history if h["hard_violations"] == 0), None) for r in rs]
        firsts = [f for f in firsts if f is not None]
        out.append(f"| {size} | {len(d.sessions)} | {_fmt([r.history[0]['hard_violations'] for r in rs], '{:.1f}')} | "
                   f"{_fmt([r.evaluation.hard_total for r in rs], '{:.1f}')} | {sum(1 for r in rs if r.is_conflict_free)}/{len(rs)} | "
                   f"{_fmt(firsts, '{:.1f}') if firsts else 'n/a'} | {_fmt([r.elapsed_seconds for r in rs])} |")
    # ---- 4. reproducibility ----
    r1, r2 = _run(data, 99, **base), _run(data, 99, **base)
    out += ["", "## 4. Reproducibility", "", f"Two runs with seed 99 produced identical best chromosomes: **{r1.best.key() == r2.best.key()}** "
            f"(fitness {r1.evaluation.fitness:.8f} and {r2.evaluation.fitness:.8f}).", ""]
    text = "\n".join(out) + "\n"
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.path.insert(0, ROOT)
    sys.exit(main())
